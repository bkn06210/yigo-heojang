package com.wallet.engine.dto;

/**
 * 홈 브리핑이 말하는 상황.
 *
 * 화면이 상황별로 다르게 꾸밀 수 있도록 응답에 함께 내려간다. 문구만 내려주면
 * 프론트가 문장을 뜯어보고 분기해야 하는데, 문구가 바뀔 때마다 그 분기가 깨진다.
 *
 * 위에 있는 것이 먼저다. 여러 상황이 동시에 성립하면 <b>사용자가 지금 할 수 있는 일이
 * 더 구체적인 쪽</b>을 고른다 — "카페는 이 카드로"가 "실적을 채우세요"보다 실행하기 쉽다.
 */
public enum BriefingType {

    /** 보유 카드가 없다. 다른 안내가 성립하지 않는다. */
    NO_CARD,

    /**
     * 결제는 하는데 그 업종 혜택을 안 쓰고 있다.
     *
     * <b>"놓친 혜택"과 다르다.</b> 지난 거래를 되짚어 "얼마 놓쳤다"를 합산하지 않는다 —
     * 그렇게 하면 거래마다 따로 계산한 값이 더해져 월 한도를 넘긴 금액이 나온다.
     * 여기서는 현재 상태만 보고 앞으로 무엇을 하면 되는지만 말한다.
     */
    UNUSED_BENEFIT,

    /** 실적 달성이 가장 임박한 카드가 있다. */
    PERFORMANCE_NEAR,

    /** 실적 조건이 있는 카드를 전부 채웠다. */
    ALL_ACHIEVED,

    /** 권할 혜택은 마땅치 않지만 이번 달 소비가 몰린 업종이 있다. */
    SPENDING_INSIGHT,

    /** 이번 달 결제 기록이 아직 없다. */
    GETTING_STARTED
}
